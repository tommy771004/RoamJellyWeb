/**
 * Pulls the official office calendar (中華民國政府行政機關辦公日曆表) published by
 * the Directorate-General of Personnel Administration on data.gov.tw
 * (dataset 14718) and writes src/data/taiwanOfficeCalendar.ts, which the
 * /holidays/{year}/ SEO page reads. Years already in the file are kept.
 *
 *   npm run sync:tw-calendar -- 2027          # one or more Gregorian years
 *
 * The calendar for a year is usually published around May–June of the
 * year before; run this once it appears.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { TW_OFFICE_CALENDARS, type OfficeCalendarYear } from '../src/data/taiwanOfficeCalendar';

const DATASET_API = 'https://data.gov.tw/api/v2/rest/dataset/14718';
const DATASET_PAGE = 'https://data.gov.tw/dataset/14718';
const OUT_FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/data/taiwanOfficeCalendar.ts');

type Resource = { resourceDescription?: string; resourceDownloadUrl?: string; resourceFormat?: string };

async function findCsvUrl(rocYear: number): Promise<string> {
  const res = await fetch(DATASET_API, { headers: { 'User-Agent': 'RoamJelly calendar sync' } });
  if (!res.ok) throw new Error(`data.gov.tw answered ${res.status}`);
  const json: any = await res.json();
  const resources: Resource[] = json?.result?.distribution ?? [];
  // The plain table, not the "_Google行事曆專用" variant; the last listed is the newest revision.
  const matches = resources.filter(
    (r) =>
      r.resourceFormat === 'CSV' &&
      r.resourceDescription?.startsWith(`${rocYear}年中華民國政府行政機關辦公日曆表`) &&
      !r.resourceDescription.includes('Google'),
  );
  const url = matches.at(-1)?.resourceDownloadUrl;
  if (!url) throw new Error(`No ${rocYear}年 calendar CSV on ${DATASET_PAGE} yet`);
  return url;
}

function parseCalendar(csv: string, year: number, sourceUrl: string): OfficeCalendarYear {
  const lines = csv.replace(/^\uFEFF/, '').split(/\r?\n/).filter((l) => l.trim());
  const header = lines.shift() ?? '';
  if (!header.includes('西元日期') || !header.includes('是否放假')) throw new Error(`Unexpected CSV header: ${header}`);

  const offDays: OfficeCalendarYear['offDays'] = [];
  const workingWeekends: string[] = [];
  let days = 0;
  for (const line of lines) {
    const [ymd, , flag, note = ''] = line.split(',');
    if (!/^\d{8}$/.test(ymd)) continue;
    days++;
    const date = `${ymd.slice(0, 4)}-${ymd.slice(4, 6)}-${ymd.slice(6, 8)}`;
    const weekday = new Date(`${date}T00:00:00Z`).getUTCDay();
    const isWeekend = weekday === 0 || weekday === 6;
    if (flag.trim() === '2') offDays.push(note.trim() ? { date, note: note.trim() } : { date });
    else if (isWeekend) workingWeekends.push(date); // 補班
  }
  if (days < 365) throw new Error(`Only ${days} days in the ${year} CSV`);
  return { year, sourceUrl, sourcePage: DATASET_PAGE, offDays, workingWeekends };
}

async function main() {
  const years = process.argv.slice(2).map(Number).filter((y) => y > 1911);
  if (years.length === 0) throw new Error('Usage: npm run sync:tw-calendar -- 2027 [2028 …]');

  const calendars: Record<number, OfficeCalendarYear> = { ...TW_OFFICE_CALENDARS };
  for (const year of years) {
    const url = await findCsvUrl(year - 1911);
    const res = await fetch(url, { headers: { 'User-Agent': 'RoamJelly calendar sync' } });
    if (!res.ok) throw new Error(`CSV download answered ${res.status}`);
    const cal = parseCalendar(await res.text(), year, url);
    calendars[year] = cal;
    console.log(`${year}: ${cal.offDays.length} days off, ${cal.workingWeekends.length} working weekend days`);
  }

  const body = JSON.stringify(Object.fromEntries(Object.keys(calendars).sort().map((k) => [k, calendars[Number(k)]])), null, 2);
  await fs.writeFile(
    OUT_FILE,
    `// AUTO-GENERATED by scripts/sync-tw-calendar.ts (npm run sync:tw-calendar -- <year>).
// Source: 行政院人事行政總處「中華民國政府行政機關辦公日曆表」, ${DATASET_PAGE} (政府資料開放授權條款).
export interface OfficeCalendarYear {
  year: number;
  sourceUrl: string;
  sourcePage: string;
  /** Every day off in the year (weekends included); \`note\` = the holiday or 補假 label. */
  offDays: Array<{ date: string; note?: string }>;
  /** Saturdays/Sundays that are working days (補班). */
  workingWeekends: string[];
}

export const TW_OFFICE_CALENDARS: Record<number, OfficeCalendarYear> = ${body};
`,
    'utf8',
  );
  console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
