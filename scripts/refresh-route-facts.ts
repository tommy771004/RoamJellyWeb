/**
 * Refreshes src/data/routeFlightFacts.ts — the nonstop-flight facts shown on
 * the /fly/{route}/ SEO pages — by scraping Trip.com for every KNOWN_ROUTE.
 *
 *   npm run sync:route-facts                     # all routes, writes the file
 *   npm run sync:route-facts -- --dry-run        # print summaries, write nothing
 *   npm run sync:route-facts -- --only=tpe-fuk   # one or more slugs, comma-separated
 *
 * Runs weekly in .github/workflows/route-facts.yml. Only real scraped rows are
 * kept (the scraper is called directly; the AI fallback in fetchFlightOffers
 * is never used). A route whose scrape returns nothing keeps its previous
 * snapshot, so one bad week never wipes a page's facts.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { scrapeTripFlights } from '../src/server/services/tripParser';
import { KNOWN_ROUTES } from '../src/server/seo/cities';
import {
  collapseCodeshares,
  parseDurationMin,
  summarizeRouteFlights,
  formatDurationRangeZh,
  type RouteFlightRow,
  type RouteFlightSnapshot,
} from '../src/server/seo/routeFlightFacts';
import { ROUTE_FLIGHT_SNAPSHOTS } from '../src/data/routeFlightFacts';

const OUT_FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/data/routeFlightFacts.ts');
/** Two departure dates on different weekdays catch more of the schedule than one. */
const DAYS_AHEAD = [21, 45];
const PAUSE_MS = 2_000;
/** Read past the app's 10-result cap so every airline on the route shows up. */
const SCRAPE_OPTS = { maxFlights: 150, scrollCapMs: 60_000 };

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const only = args.find((a) => a.startsWith('--only='))?.slice('--only='.length).split(',').filter(Boolean);

const isoDate = (daysAhead: number) => new Date(Date.now() + daysAhead * 864e5).toISOString().slice(0, 10);
const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

async function scrapeRoute(fromCode: string, toCode: string): Promise<RouteFlightRow[]> {
  const byFlight = new Map<string, RouteFlightRow>();
  for (const days of DAYS_AHEAD) {
    const date = isoDate(days);
    const rows = await scrapeTripFlights(fromCode, toCode, date, SCRAPE_OPTS).catch((err) => {
      console.warn(`  ${fromCode}-${toCode} ${date}: scrape failed — ${err?.message ?? err}`);
      return [];
    });
    for (const row of rows) {
      const d = row.details;
      if (!d || d.stops !== 0) continue;
      // A city search can return the other airport (NRT vs HND); keep the one this page is about.
      if (d.arrCode && d.arrCode.toUpperCase() !== toCode) continue;
      if (d.depCode && d.depCode.toUpperCase() !== fromCode) continue;
      const durationMin = parseDurationMin(d.duration);
      if (!durationMin || !(row.price > 0)) continue;
      const flightNumber = String(d.flightNumber ?? '').trim();
      const key = flightNumber || `${d.airline}-${d.departure}`;
      const candidate: RouteFlightRow = {
        airline: String(d.airline).trim(),
        flightNumber,
        departure: d.departure,
        arrival: d.arrival,
        durationMin,
        price: Math.round(row.price),
        departureDate: date,
      };
      const existing = byFlight.get(key);
      if (!existing || candidate.price < existing.price) byFlight.set(key, candidate);
    }
    await sleep(PAUSE_MS);
  }
  return collapseCodeshares([...byFlight.values()]).sort((a, b) => a.departure.localeCompare(b.departure));
}

function renderDataFile(snapshots: Record<string, RouteFlightSnapshot>): string {
  const ordered = Object.fromEntries(Object.keys(snapshots).sort().map((k) => [k, snapshots[k]]));
  return `// AUTO-GENERATED by scripts/refresh-route-facts.ts (npm run sync:route-facts).
// Do not edit by hand: the weekly workflow overwrites this file.
import type { RouteFlightSnapshot } from '../server/seo/routeFlightFacts';

export const ROUTE_FLIGHT_SNAPSHOTS: Record<string, RouteFlightSnapshot> = ${JSON.stringify(ordered, null, 2)};
`;
}

async function main() {
  const routes = KNOWN_ROUTES.filter((r) => !only || only.includes(r.slug));
  if (routes.length === 0) throw new Error(`No route matches --only=${only?.join(',')}`);

  const snapshots: Record<string, RouteFlightSnapshot> = { ...ROUTE_FLIGHT_SNAPSHOTS };
  let refreshed = 0;
  let kept = 0;

  for (const route of routes) {
    const flights = await scrapeRoute(route.fromCode, route.toCode);
    if (flights.length === 0) {
      kept++;
      console.log(`${route.slug}: no nonstop flights scraped — keeping the previous snapshot${snapshots[route.slug] ? '' : ' (none)'}`);
      continue;
    }
    const snapshot: RouteFlightSnapshot = { slug: route.slug, fetchedAt: new Date().toISOString(), flights };
    const summary = summarizeRouteFlights(snapshot);
    snapshots[route.slug] = snapshot;
    refreshed++;
    console.log(
      `${route.slug}: ${flights.length} nonstop flights, ` +
        `${summary ? formatDurationRangeZh(summary.minDurationMin, summary.maxDurationMin) : '-'}, ` +
        `airlines: ${summary?.airlines.map((a) => a.name).join('、') ?? '-'}, ` +
        `lowest NT$${summary?.minPrice ?? '-'}`,
    );
  }

  console.log(`\nRefreshed ${refreshed}, kept previous for ${kept}.`);
  if (dryRun) {
    console.log('Dry run: nothing written.');
    return;
  }
  await fs.writeFile(OUT_FILE, renderDataFile(snapshots), 'utf8');
  console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error(err);
    process.exit(1);
  });
